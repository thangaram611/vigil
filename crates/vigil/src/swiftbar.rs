//! The SwiftBar menu-bar plugin: a two-line shim that execs `vigil menubar`.
//!
//! SwiftBar is optional. `vigil setup` writes the shim only when SwiftBar has a
//! plugin folder configured; `vigil uninstall` removes it. All menu logic lives
//! in `vigil menubar` — the shim exists because SwiftBar runs files, and takes
//! the refresh interval from the file name (`vigil.5s.sh` → every 5 seconds).

use std::io;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};

/// `{name}.{interval}.{ext}` — SwiftBar reads the refresh interval from here.
pub const PLUGIN_FILE: &str = "vigil.5s.sh";

/// SwiftBar's configured plugin folder, or `None` when SwiftBar is not set up.
/// `VIGIL_SWIFTBAR_PLUGIN_DIR` overrides the lookup (empty = not configured).
pub fn plugin_dir() -> Option<PathBuf> {
    let dir = match std::env::var("VIGIL_SWIFTBAR_PLUGIN_DIR") {
        Ok(v) => v,
        Err(_) => std::process::Command::new("/usr/bin/defaults")
            .args(["read", "com.ameba.SwiftBar", "PluginDirectory"])
            .stderr(std::process::Stdio::null())
            .output()
            .ok()
            .filter(|o| o.status.success())
            .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())?,
    };
    let dir = PathBuf::from(dir);
    dir.is_dir().then_some(dir)
}

/// The shim body. The `<swiftbar.hide*>` tags drop SwiftBar's own boilerplate
/// items so the menu holds only Vigil's.
pub fn render_plugin(vigil_bin: &str) -> String {
    format!(
        "#!/bin/sh\n\
         # Generated by `vigil setup`. All logic lives in `vigil menubar`.\n\
         # <xbar.title>Vigil</xbar.title>\n\
         # <xbar.desc>Sleep-hold state and manual mode for Vigil.</xbar.desc>\n\
         # <xbar.author.github>thangaram611</xbar.author.github>\n\
         # <swiftbar.hideAbout>true</swiftbar.hideAbout>\n\
         # <swiftbar.hideRunInTerminal>true</swiftbar.hideRunInTerminal>\n\
         # <swiftbar.hideLastUpdated>true</swiftbar.hideLastUpdated>\n\
         # <swiftbar.hideDisablePlugin>true</swiftbar.hideDisablePlugin>\n\
         # <swiftbar.hideSwiftBar>true</swiftbar.hideSwiftBar>\n\
         exec '{}' menubar\n",
        vigil_bin.replace('\'', "'\\''"),
    )
}

/// Write the executable shim into `dir`, replacing any previous one.
pub fn install(dir: &Path, vigil_bin: &str) -> io::Result<PathBuf> {
    let plugin = dir.join(PLUGIN_FILE);
    std::fs::write(&plugin, render_plugin(vigil_bin))?;
    std::fs::set_permissions(&plugin, std::fs::Permissions::from_mode(0o755))?;
    Ok(plugin)
}

/// Remove the shim from `dir`. `Ok(false)` when there was none.
pub fn remove(dir: &Path) -> io::Result<bool> {
    match std::fs::remove_file(dir.join(PLUGIN_FILE)) {
        Ok(()) => Ok(true),
        Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(false),
        Err(e) => Err(e),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shim_execs_the_given_binary_and_survives_quotes_and_spaces() {
        let body = render_plugin("/Users/x/Library/Application Support/vigil/bin/vigil");
        assert!(body.starts_with("#!/bin/sh\n"));
        assert!(
            body.ends_with("exec '/Users/x/Library/Application Support/vigil/bin/vigil' menubar\n")
        );
        assert!(render_plugin("/o'dd/vigil").ends_with("exec '/o'\\''dd/vigil' menubar\n"));
    }

    #[test]
    fn install_is_executable_and_idempotent_and_remove_reports_presence() {
        let dir = tempfile::tempdir().unwrap();
        let plugin = install(dir.path(), "/bin/vigil").unwrap();
        assert_eq!(plugin, dir.path().join(PLUGIN_FILE));
        let mode = std::fs::metadata(&plugin).unwrap().permissions().mode();
        assert_eq!(mode & 0o777, 0o755);
        install(dir.path(), "/other/vigil").unwrap();
        assert!(
            std::fs::read_to_string(&plugin)
                .unwrap()
                .contains("'/other/vigil'")
        );
        assert!(remove(dir.path()).unwrap());
        assert!(!remove(dir.path()).unwrap(), "already gone");
    }

    #[test]
    fn the_shim_runs_and_forwards_to_menubar() {
        // A stand-in `vigil` that echoes its argv proves the shim is valid sh.
        let dir = tempfile::tempdir().unwrap();
        let fake = dir.path().join("fake vigil");
        std::fs::write(&fake, "#!/bin/sh\necho \"got:$*\"\n").unwrap();
        std::fs::set_permissions(&fake, std::fs::Permissions::from_mode(0o755)).unwrap();
        let plugin = install(dir.path(), fake.to_str().unwrap()).unwrap();
        let out = std::process::Command::new(&plugin).output().unwrap();
        assert_eq!(String::from_utf8_lossy(&out.stdout), "got:menubar\n");
    }
}
